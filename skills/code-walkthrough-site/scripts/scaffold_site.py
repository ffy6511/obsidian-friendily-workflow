#!/usr/bin/env python3
"""Scaffold a self-contained progressive code-walkthrough website.

Copies the skill template, embeds content JSON as content.js, and prints
one-command launch instructions.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

SKILL_ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_DIR = SKILL_ROOT / "assets" / "template"
EXAMPLE_CONTENT = TEMPLATE_DIR / "content.example.json"

COPY_NAMES = (
    "index.html",
    "styles.css",
    "app.js",
)


def load_content(path: Path) -> dict:
    with path.open("r", encoding="utf-8") as fh:
        data = json.load(fh)
    if not isinstance(data, dict):
        raise ValueError("content root must be an object")
    return data


def write_content_js(target: Path, data: dict) -> None:
    # JSON is a subset of JS object literals for our data; embed safely via JSON.stringify equivalent.
    payload = json.dumps(data, ensure_ascii=False, indent=2)
    target.write_text(
        "// Generated by code-walkthrough-site scaffold. Do not edit by hand unless you mean it.\n"
        f"window.SITE_CONTENT = {payload};\n",
        encoding="utf-8",
    )


def copy_template(dest: Path, force: bool) -> None:
    if dest.exists():
        if not force and any(dest.iterdir()):
            raise FileExistsError(
                f"destination is not empty: {dest} (pass --force to overwrite template files)"
            )
    dest.mkdir(parents=True, exist_ok=True)

    for name in COPY_NAMES:
        src = TEMPLATE_DIR / name
        if not src.is_file():
            raise FileNotFoundError(f"template missing: {src}")
        shutil.copy2(src, dest / name)

    vendor_src = TEMPLATE_DIR / "vendor"
    vendor_dest = dest / "vendor"
    if vendor_dest.exists():
        shutil.rmtree(vendor_dest)
    shutil.copytree(vendor_src, vendor_dest)


def copy_figures(figures: Path | None, dest: Path) -> None:
    if not figures:
        return
    if not figures.is_dir():
        raise FileNotFoundError(f"figures directory not found: {figures}")
    target = dest / "figures"
    if target.exists():
        shutil.rmtree(target)
    shutil.copytree(figures, target)


def write_package_json(dest: Path, title: str) -> None:
    pkg = {
        "name": "code-walkthrough-site",
        "private": True,
        "version": "0.0.0",
        "description": title,
        "scripts": {
            "start": "python3 -m http.server 4173 --bind 127.0.0.1",
            "dev": "python3 -m http.server 4173 --bind 127.0.0.1",
        },
    }
    (dest / "package.json").write_text(
        json.dumps(pkg, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def write_readme(dest: Path, title: str) -> None:
    text = f"""# {title}

Self-contained progressive code walkthrough (left prose, right reveal).

## Launch

```bash
cd {dest.name}
python3 -m http.server 4173 --bind 127.0.0.1
```

Open http://127.0.0.1:4173/

Or: `npm start` (same server).

## Edit content

1. Edit `content.source.json`
2. Regenerate `content.js`:

```bash
python3 -c "import json,pathlib; p=pathlib.Path('content.source.json'); t=pathlib.Path('content.js'); t.write_text('window.SITE_CONTENT = '+json.dumps(json.loads(p.read_text()),ensure_ascii=False,indent=2)+';\\n', encoding='utf-8')"
```

Prefer re-running the skill scaffold script after content changes.
"""
    (dest / "README.md").write_text(text, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--content",
        type=Path,
        default=EXAMPLE_CONTENT,
        help="Path to content JSON (default: template example)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="Output directory for the generated site",
    )
    parser.add_argument(
        "--figures",
        type=Path,
        default=None,
        help="Optional figures directory to copy into site/figures",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="Overwrite template files in an existing destination",
    )
    parser.add_argument(
        "--skip-validate",
        action="store_true",
        help="Skip content validation",
    )
    args = parser.parse_args()

    content_path = args.content.resolve()
    out = args.out.resolve()

    if not content_path.is_file():
        print(f"error: content not found: {content_path}", file=sys.stderr)
        return 2

    if not args.skip_validate:
        # Import sibling validator without package install.
        sys.path.insert(0, str(Path(__file__).resolve().parent))
        from validate_content import validate  # type: ignore

        data = load_content(content_path)
        errors = validate(data)
        if errors:
            print(f"error: content validation failed ({len(errors)}):", file=sys.stderr)
            for err in errors:
                print(f"  - {err}", file=sys.stderr)
            return 1
    else:
        data = load_content(content_path)

    try:
        copy_template(out, force=args.force)
        write_content_js(out / "content.js", data)
        # Keep an editable source next to the site.
        shutil.copy2(content_path, out / "content.source.json")
        copy_figures(args.figures.resolve() if args.figures else None, out)
        title = (data.get("site") or {}).get("title") or "Code Walkthrough"
        write_package_json(out, title)
        write_readme(out, title)
    except (FileExistsError, FileNotFoundError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1

    print(f"OK scaffolded {out}")
    print("Launch:")
    print(f"  cd {out}")
    print("  python3 -m http.server 4173 --bind 127.0.0.1")
    print("  open http://127.0.0.1:4173/")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
